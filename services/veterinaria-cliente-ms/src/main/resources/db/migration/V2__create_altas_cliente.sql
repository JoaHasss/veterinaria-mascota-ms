-- S9: registro de cada evento usuario.registrado ya procesado (saga de alta
-- de cliente). Es la evidencia de idempotencia del consumidor: una fila por
-- usuario, con el resultado (CREADO o RECHAZADO). uk_altas_cliente_usuario
-- impide un segundo procesamiento aunque dos entregas lleguen a la vez.
CREATE TABLE IF NOT EXISTS altas_cliente (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id    BIGINT       NOT NULL,
    email         VARCHAR(150) NOT NULL,
    resultado     VARCHAR(20)  NOT NULL,
    motivo        VARCHAR(255),
    cliente_id    BIGINT,
    fecha_proceso TIMESTAMP    NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_altas_cliente_usuario UNIQUE (usuario_id)
);
