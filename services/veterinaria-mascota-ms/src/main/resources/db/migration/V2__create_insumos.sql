-- S9 (Parte E): inventario de insumos clinicos que una cita puede reservar.
-- citas-ms descuenta el stock al crear la cita y lo devuelve si la cita se
-- compensa (pago.fallido).
CREATE TABLE IF NOT EXISTS insumos (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    tipo   VARCHAR(30)  NOT NULL,
    stock  INTEGER      NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_insumos_stock CHECK (stock >= 0)
);

